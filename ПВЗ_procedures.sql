-- 2.2. Обновление данных клиента (UPDATE)
-- Назначение: изменить контактные данные клиента
-- Параметры: @КлиентID, @ФИО, @Телефон, @Email
CREATE OR ALTER PROCEDURE proc_Клиенты_Update
    @КлиентID INT,
    @ФИО      NVARCHAR(150),
    @Телефон  VARCHAR(20),
    @Email    VARCHAR(100) = NULL
AS
BEGIN
    SET NOCOUNT ON;
    IF NOT EXISTS (SELECT 1 FROM Клиенты WHERE КлиентID = @КлиентID)
    BEGIN
        THROW 50001, N'Клиент не найден', 1;
        RETURN;
    END
    IF EXISTS (SELECT 1 FROM Клиенты WHERE Телефон = @Телефон AND КлиентID <> @КлиентID)
    BEGIN
        THROW 50003, N'Телефон уже используется другим клиентом', 1;
        RETURN;
    END
    UPDATE Клиенты
    SET ФИО = @ФИО, Телефон = @Телефон, Email = @Email
    WHERE КлиентID = @КлиентID;
END
GO
-- Вызов: EXEC proc_Клиенты_Update @КлиентID = 1, @ФИО = N'Алексеева Ольга Н.', @Телефон = '+79161112233';

-- 2.3. Создание заказа (INSERT, с OUTPUT-параметром)
-- Назначение: зарегистрировать новое отправление, вернуть ID
-- Параметры: @ТрекНомер, @КлиентID, @ПоставщикID, @СрокХраненияДо,
--            @СтоимостьТовара, @НаложенныйПлатёж, @ЗаказID OUTPUT
CREATE OR ALTER PROCEDURE proc_Заказы_Create
    @ТрекНомер        VARCHAR(30),
    @КлиентID         INT,
    @ПоставщикID      INT,
    @СрокХраненияДо   DATE,
    @СтоимостьТовара  DECIMAL(10,2),
    @НаложенныйПлатёж BIT = 0,
    @ЗаказID          INT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    IF NOT EXISTS (SELECT 1 FROM Клиенты WHERE КлиентID = @КлиентID)
    BEGIN
        THROW 50001, N'Клиент не найден', 1;
        RETURN;
    END
    IF NOT EXISTS (SELECT 1 FROM Поставщики WHERE ПоставщикID = @ПоставщикID)
    BEGIN
        THROW 50004, N'Поставщик не найден', 1;
        RETURN;
    END
    IF @СтоимостьТовара < 0
    BEGIN
        THROW 50005, N'Стоимость товара не может быть отрицательной', 1;
        RETURN;
    END
    INSERT INTO Заказы (ТрекНомер, КлиентID, ПоставщикID, СрокХраненияДо, СтоимостьТовара, НаложенныйПлатёж, Статус)
    VALUES (@ТрекНомер, @КлиентID, @ПоставщикID, @СрокХраненияДо, @СтоимостьТовара, @НаложенныйПлатёж, 'в пути');
    SET @ЗаказID = SCOPE_IDENTITY();
END
GO
