-- 4.1. Разместить заказ в ячейке
-- Назначение: при приёмке отправления поместить заказ в свободную ячейку
--             и изменить статус заказа и ячейки атомарно (две таблицы)
-- Параметры: @ЗаказID, @ЯчейкаID
CREATE OR ALTER PROCEDURE proc_Заказы_ПоместитьВЯчейку
    @ЗаказID  INT,
    @ЯчейкаID INT
AS
BEGIN
    SET NOCOUNT ON;
    BEGIN TRY
        BEGIN TRANSACTION;

        IF NOT EXISTS (SELECT 1 FROM Заказы WHERE ЗаказID = @ЗаказID)
            THROW 50006, N'Заказ не найден', 1;

        IF NOT EXISTS (SELECT 1 FROM Ячейки WHERE ЯчейкаID = @ЯчейкаID AND Статус = 'свободна')
            THROW 50010, N'Ячейка не найдена или уже занята', 1;

        UPDATE Заказы
        SET ЯчейкаID = @ЯчейкаID, Статус = 'на складе'
        WHERE ЗаказID = @ЗаказID;

        UPDATE Ячейки
        SET Статус = 'занята'
        WHERE ЯчейкаID = @ЯчейкаID;

        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF XACT_STATE() <> 0
            ROLLBACK TRANSACTION;
        THROW;
    END CATCH
END
GO
-- Вызов: EXEC proc_Заказы_ПоместитьВЯчейку @ЗаказID = 27, @ЯчейкаID = 3;

-- 4.2. Выдать заказ клиенту
-- Назначение: оформить выдачу — записать в Выдачи, перевести заказ в статус
--             'выдан', освободить ячейку хранения. Атомарная операция
--             на трёх таблицах (Выдачи, Заказы, Ячейки).
-- Параметры: @ЗаказID, @СотрудникID, @СпособОплаты, @Сумма
CREATE OR ALTER PROCEDURE proc_Заказы_Выдать
    @ЗаказID      INT,
    @СотрудникID  INT,
    @СпособОплаты VARCHAR(20) = NULL,
    @Сумма        DECIMAL(10,2) = NULL
AS
BEGIN
    SET NOCOUNT ON;
    BEGIN TRY
        BEGIN TRANSACTION;

        DECLARE @Статус VARCHAR(20), @ЯчейкаID INT;
        SELECT @Статус = Статус, @ЯчейкаID = ЯчейкаID FROM Заказы WHERE ЗаказID = @ЗаказID;

        IF @Статус IS NULL
            THROW 50006, N'Заказ не найден', 1;
        IF @Статус <> 'на складе'
            THROW 50011, N'Выдать можно только заказ со статусом "на складе"', 1;
        IF NOT EXISTS (SELECT 1 FROM Сотрудники WHERE СотрудникID = @СотрудникID)
            THROW 50012, N'Сотрудник не найден', 1;

        INSERT INTO Выдачи (ЗаказID, СотрудникID, СпособОплаты, СуммаОплачена)
        VALUES (@ЗаказID, @СотрудникID, @СпособОплаты, @Сумма);

        UPDATE Заказы SET Статус = 'выдан' WHERE ЗаказID = @ЗаказID;

        IF @ЯчейкаID IS NOT NULL
            UPDATE Ячейки SET Статус = 'свободна' WHERE ЯчейкаID = @ЯчейкаID;

        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF XACT_STATE() <> 0
            ROLLBACK TRANSACTION;
        THROW;
    END CATCH
END
GO
-- Вызов: EXEC proc_Заказы_Выдать @ЗаказID = 11, @СотрудникID = 2, @СпособОплаты = 'карта', @Сумма = 2590.00;

-- 4.3. Оформить возврат заказа
-- Назначение: зафиксировать возврат, перевести заказ в статус 'возврат',
--             освободить ячейку, если была занята. Атомарная операция.
-- Параметры: @ЗаказID, @Причина
CREATE OR ALTER PROCEDURE proc_Заказы_ОформитьВозврат
    @ЗаказID INT,
    @Причина NVARCHAR(200)
AS
BEGIN
    SET NOCOUNT ON;
    BEGIN TRY
        BEGIN TRANSACTION;

        DECLARE @ЯчейкаID INT;
        IF NOT EXISTS (SELECT 1 FROM Заказы WHERE ЗаказID = @ЗаказID)
            THROW 50006, N'Заказ не найден', 1;

        SELECT @ЯчейкаID = ЯчейкаID FROM Заказы WHERE ЗаказID = @ЗаказID;

        INSERT INTO Возвраты (ЗаказID, Причина)
        VALUES (@ЗаказID, @Причина);

        UPDATE Заказы SET Статус = 'возврат' WHERE ЗаказID = @ЗаказID;

        IF @ЯчейкаID IS NOT NULL
            UPDATE Ячейки SET Статус = 'свободна' WHERE ЯчейкаID = @ЯчейкаID;

        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF XACT_STATE() <> 0
            ROLLBACK TRANSACTION;
        THROW;
    END CATCH
END
GO
-- Вызов: EXEC proc_Заказы_ОформитьВозврат @ЗаказID = 13, @Причина = N'Брак товара';

