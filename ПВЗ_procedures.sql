-- 5.1. Выручка по наложенным платежам за период
-- Назначение: суммарная выручка и количество выдач по дням за период
-- Параметры: @ДатаС, @ДатаПо
CREATE OR ALTER PROCEDURE proc_Отчёт_ВыручкаЗаПериод
    @ДатаС DATE,
    @ДатаПо DATE
AS
BEGIN
    SET NOCOUNT ON;
    IF @ДатаС > @ДатаПо
    BEGIN
        THROW 50013, N'Начало периода позже окончания', 1;
        RETURN;
    END
    SELECT CAST(в.ДатаВыдачи AS DATE) AS Дата,
           COUNT(*) AS КоличествоВыдач,
           SUM(ISNULL(в.СуммаОплачена, 0)) AS Выручка
    FROM Выдачи в
    WHERE CAST(в.ДатаВыдачи AS DATE) BETWEEN @ДатаС AND @ДатаПо
    GROUP BY CAST(в.ДатаВыдачи AS DATE)
    ORDER BY Дата;
END
GO
-- Вызов: EXEC proc_Отчёт_ВыручкаЗаПериод @ДатаС = '2026-10-01', @ДатаПо = '2026-10-31';

-- 5.2. Заказы по поставщикам за период
-- Назначение: количество заказов и сумма стоимости товаров по каждому поставщику
-- Параметры: @ДатаС, @ДатаПо
CREATE OR ALTER PROCEDURE proc_Отчёт_ЗаказыПоПоставщикам
    @ДатаС  DATE,
    @ДатаПо DATE
AS
BEGIN
    SET NOCOUNT ON;
    IF @ДатаС > @ДатаПо
    BEGIN
        THROW 50013, N'Начало периода позже окончания', 1;
        RETURN;
    END
    SELECT п.Название AS Поставщик,
           COUNT(з.ЗаказID) AS КоличествоЗаказов,
           SUM(з.СтоимостьТовара) AS СуммаТоваров,
           AVG(з.СтоимостьТовара) AS СредняяСтоимость
    FROM Заказы з
    JOIN Поставщики п ON п.ПоставщикID = з.ПоставщикID
    WHERE CAST(з.ДатаПоступления AS DATE) BETWEEN @ДатаС AND @ДатаПо
    GROUP BY п.Название
    ORDER BY КоличествоЗаказов DESC;
END
GO
-- Вызов: EXEC proc_Отчёт_ЗаказыПоПоставщикам @ДатаС = '2026-10-01', @ДатаПо = '2026-10-31';

-- 5.3. Загруженность ячеек хранения по размерам
-- Назначение: количество свободных/занятых ячеек в разрезе размера
-- Параметры: нет
CREATE OR ALTER PROCEDURE proc_Отчёт_ЗагруженностьЯчеек
AS
BEGIN
    SET NOCOUNT ON;
    SELECT Размер, Статус, COUNT(*) AS Количество
    FROM Ячейки
    GROUP BY Размер, Статус
    ORDER BY Размер, Статус;
END
GO
-- Вызов: EXEC proc_Отчёт_ЗагруженностьЯчеек;

