-- 2.4. Изменение статуса заказа (UPDATE)
-- Назначение: сменить статус заказа с проверкой допустимого значения
-- Параметры: @ЗаказID, @НовыйСтатус
CREATE OR ALTER PROCEDURE proc_Заказы_UpdateStatus
    @ЗаказID     INT,
    @НовыйСтатус VARCHAR(20)
AS
BEGIN
    SET NOCOUNT ON;
    IF NOT EXISTS (SELECT 1 FROM Заказы WHERE ЗаказID = @ЗаказID)
    BEGIN
        THROW 50006, N'Заказ не найден', 1;
        RETURN;
    END
    IF @НовыйСтатус NOT IN ('в пути','на складе','выдан','возврат')
    BEGIN
        THROW 50002, N'Недопустимое значение статуса', 1;
        RETURN;
    END
    UPDATE Заказы SET Статус = @НовыйСтатус WHERE ЗаказID = @ЗаказID;
END
GO
-- Вызов: EXEC proc_Заказы_UpdateStatus @ЗаказID = 27, @НовыйСтатус = 'на складе';

-- 2.5. Удаление ячейки (DELETE, с учётом ссылочной целостности)
-- Назначение: удалить ячейку хранения, если она не используется активно
-- Параметры: @ЯчейкаID
CREATE OR ALTER PROCEDURE proc_Ячейки_Delete
    @ЯчейкаID INT
AS
BEGIN
    SET NOCOUNT ON;
    IF NOT EXISTS (SELECT 1 FROM Ячейки WHERE ЯчейкаID = @ЯчейкаID)
    BEGIN
        THROW 50007, N'Ячейка не найдена', 1;
        RETURN;
    END
    IF EXISTS (SELECT 1 FROM Заказы WHERE ЯчейкаID = @ЯчейкаID AND Статус IN ('на складе'))
    BEGIN
        THROW 50008, N'Ячейка занята активным заказом, удаление невозможно', 1;
        RETURN;
    END
    -- FK Заказы.ЯчейкаID объявлен с ON DELETE SET NULL, поэтому исторические
    -- (уже выданные) заказы при удалении ячейки не теряются
    DELETE FROM Ячейки WHERE ЯчейкаID = @ЯчейкаID;
END
GO
-- Вызов: EXEC proc_Ячейки_Delete @ЯчейкаID = 9;

-- 2.6. Удаление клиента (DELETE, только при отсутствии заказов)
-- Назначение: удалить клиента, если на него нет ссылок в Заказах
-- Параметры: @КлиентID
CREATE OR ALTER PROCEDURE proc_Клиенты_Delete
    @КлиентID INT
AS
BEGIN
    SET NOCOUNT ON;
    IF NOT EXISTS (SELECT 1 FROM Клиенты WHERE КлиентID = @КлиентID)
    BEGIN
        THROW 50001, N'Клиент не найден', 1;
        RETURN;
    END
    IF EXISTS (SELECT 1 FROM Заказы WHERE КлиентID = @КлиентID)
    BEGIN
        THROW 50009, N'У клиента есть заказы, удаление запрещено ссылочной целостностью', 1;
        RETURN;
    END
    DELETE FROM Клиенты WHERE КлиентID = @КлиентID;
END
GO
-- Вызов: EXEC proc_Клиенты_Delete @КлиентID = 99;

