-- 1.1. Все клиенты
-- Назначение: вернуть полный список клиентов
-- Параметры: нет
-- Результат: набор строк Клиенты
CREATE OR ALTER PROCEDURE proc_Клиенты_GetAll
AS
BEGIN
    SET NOCOUNT ON;
    SELECT КлиентID, ФИО, Телефон, Email, КодПолучения
    FROM Клиенты
    ORDER BY ФИО;
END
GO
-- Вызов: EXEC proc_Клиенты_GetAll;

-- 1.2. Клиент по идентификатору
-- Назначение: вернуть одного клиента по КлиентID
-- Параметры: @КлиентID INT
-- Результат: одна строка Клиенты
CREATE OR ALTER PROCEDURE proc_Клиенты_GetById
    @КлиентID INT
AS
BEGIN
    SET NOCOUNT ON;
    IF NOT EXISTS (SELECT 1 FROM Клиенты WHERE КлиентID = @КлиентID)
    BEGIN
        THROW 50001, N'Клиент не найден', 1;
        RETURN;
    END
    SELECT КлиентID, ФИО, Телефон, Email, КодПолучения
    FROM Клиенты
    WHERE КлиентID = @КлиентID;
END
GO
-- Вызов: EXEC proc_Клиенты_GetById @КлиентID = 1;

-- 1.3. Заказы клиента (фильтр по клиенту, необязательный статус)
-- Назначение: вернуть заказы указанного клиента, опционально отфильтрованные по статусу
-- Параметры: @КлиентID INT, @Статус VARCHAR(20) = NULL
-- Результат: набор строк Заказы с именем поставщика и номером ячейки
CREATE OR ALTER PROCEDURE proc_Заказы_GetByClient
    @КлиентID INT,
    @Статус   VARCHAR(20) = NULL
AS
BEGIN
    SET NOCOUNT ON;
    IF NOT EXISTS (SELECT 1 FROM Клиенты WHERE КлиентID = @КлиентID)
    BEGIN
        THROW 50001, N'Клиент не найден', 1;
        RETURN;
    END
    SELECT з.ЗаказID, з.ТрекНомер, п.Название AS Поставщик, я.Номер AS Ячейка,
           з.ДатаПоступления, з.СрокХраненияДо, з.СтоимостьТовара, з.Статус
    FROM Заказы з
    JOIN Поставщики п ON п.ПоставщикID = з.ПоставщикID
    LEFT JOIN Ячейки я ON я.ЯчейкаID = з.ЯчейкаID
    WHERE з.КлиентID = @КлиентID
      AND (@Статус IS NULL OR з.Статус = @Статус)
    ORDER BY з.ДатаПоступления DESC;
END
GO
-- Вызов: EXEC proc_Заказы_GetByClient @КлиентID = 1;
-- Вызов с фильтром: EXEC proc_Заказы_GetByClient @КлиентID = 1, @Статус = 'выдан';

-- 1.4. Заказы по статусу (фильтр, используется для списка «на складе» и т.п.)
-- Назначение: вернуть все заказы с указанным статусом
-- Параметры: @Статус VARCHAR(20)
-- Результат: набор строк Заказы
CREATE OR ALTER PROCEDURE proc_Заказы_GetByStatus
    @Статус VARCHAR(20)
AS
BEGIN
    SET NOCOUNT ON;
    IF @Статус NOT IN ('в пути','на складе','выдан','возврат')
    BEGIN
        THROW 50002, N'Недопустимое значение статуса', 1;
        RETURN;
    END
    SELECT з.ЗаказID, з.ТрекНомер, к.ФИО AS Клиент, я.Номер AS Ячейка,
           з.ДатаПоступления, з.СрокХраненияДо
    FROM Заказы з
    JOIN Клиенты к ON к.КлиентID = з.КлиентID
    LEFT JOIN Ячейки я ON я.ЯчейкаID = з.ЯчейкаID
    WHERE з.Статус = @Статус
    ORDER BY з.ДатаПоступления;
END
GO
-- Вызов: EXEC proc_Заказы_GetByStatus @Статус = 'на складе';

-- 1.5. Свободные ячейки (фильтр по размеру, необязательный)
-- Назначение: вернуть список свободных ячеек, опционально нужного размера
-- Параметры: @Размер VARCHAR(10) = NULL
-- Результат: набор строк Ячейки
CREATE OR ALTER PROCEDURE proc_Ячейки_GetFree
    @Размер VARCHAR(10) = NULL
AS
BEGIN
    SET NOCOUNT ON;
    SELECT ЯчейкаID, Номер, Размер
    FROM Ячейки
    WHERE Статус = 'свободна'
      AND (@Размер IS NULL OR Размер = @Размер)
    ORDER BY Размер, Номер;
END
GO
-- Вызов: EXEC proc_Ячейки_GetFree;
-- Вызов с фильтром: EXEC proc_Ячейки_GetFree @Размер = 'M';

-- 1.6. Заказ по трек-номеру
-- Назначение: быстрый поиск заказа по трек-номеру (часто используемая операция на выдаче)
-- Параметры: @ТрекНомер VARCHAR(30)
-- Результат: одна строка с данными заказа, клиента и ячейки
CREATE OR ALTER PROCEDURE proc_Заказы_GetByTrack
    @ТрекНомер VARCHAR(30)
AS
BEGIN
    SET NOCOUNT ON;
    SELECT з.ЗаказID, з.ТрекНомер, к.ФИО AS Клиент, к.КодПолучения,
           я.Номер AS Ячейка, з.Статус, з.НаложенныйПлатёж, з.СтоимостьТовара
    FROM Заказы з
    JOIN Клиенты к ON к.КлиентID = з.КлиентID
    LEFT JOIN Ячейки я ON я.ЯчейкаID = з.ЯчейкаID
    WHERE з.ТрекНомер = @ТрекНомер;
END
GO
-- Вызов: EXEC proc_Заказы_GetByTrack @ТрекНомер = 'WB0001RU';

