-- 2.1. Создание клиента (INSERT, с OUTPUT-параметром)
-- Назначение: добавить нового клиента, вернуть его ID
-- Параметры: @ФИО, @Телефон, @Email, @КодПолучения, @КлиентID OUTPUT
CREATE OR ALTER PROCEDURE proc_Клиенты_Create
    @ФИО          NVARCHAR(150),
    @Телефон      VARCHAR(20),
    @Email        VARCHAR(100) = NULL,
    @КодПолучения CHAR(4),
    @КлиентID     INT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    IF EXISTS (SELECT 1 FROM Клиенты WHERE Телефон = @Телефон)
    BEGIN
        THROW 50003, N'Клиент с таким телефоном уже существует', 1;
        RETURN;
    END
    INSERT INTO Клиенты (ФИО, Телефон, Email, КодПолучения)
    VALUES (@ФИО, @Телефон, @Email, @КодПолучения);
    SET @КлиентID = SCOPE_IDENTITY();
END
GO
