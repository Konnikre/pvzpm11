-- ---------- Блок А. Корректные операции и аудит (в транзакции, затем откат)
BEGIN TRANSACTION;

    -- Тест 1. UPDATE: переход «в пути» -> «на складе» + назначение ячейки 3
    UPDATE Заказы SET Статус = 'на складе', ЯчейкаID = 3 WHERE ТрекНомер = 'WB0027RU';
    SELECT N'Тест 1: UPDATE' AS Тест, ИмяТаблицы, КлючЗаписи, Операция, Поле, СтароеЗначение, НовоеЗначение
    FROM АудитИзменений ORDER BY АудитID;                       -- ожидается 2 строки

    -- Тест 2. INSERT одного заказа
    INSERT INTO Заказы (ТрекНомер, КлиентID, ПоставщикID, СрокХраненияДо, СтоимостьТовара)
    VALUES ('TEST0001RU', 1, 1, '2026-11-20', 100.00);
    SELECT N'Тест 2: INSERT' AS Тест, Операция, НовоеЗначение
    FROM АудитИзменений WHERE Операция = 'INSERT' ORDER BY АудитID;   -- 1 строка

    -- Тест 3. DELETE этого заказа
    DELETE FROM Заказы WHERE ТрекНомер = 'TEST0001RU';
    SELECT N'Тест 3: DELETE' AS Тест, Операция, СтароеЗначение
    FROM АудитИзменений WHERE Операция = 'DELETE' ORDER BY АудитID;   -- 1 строка

    -- Тест 4. Многострочный INSERT (2 заказа одним оператором)
    INSERT INTO Заказы (ТрекНомер, КлиентID, ПоставщикID, СрокХраненияДо, СтоимостьТовара)
    VALUES ('TEST0002RU', 2, 2, '2026-11-20', 200.00),
           ('TEST0003RU', 3, 3, '2026-11-20', 300.00);
    SELECT N'Тест 4: многострочный INSERT' AS Тест, COUNT(*) AS СтрокАудита
    FROM АудитИзменений
    WHERE Операция = 'INSERT' AND НовоеЗначение LIKE N'ТрекНомер=TEST000[23]RU%';  -- 2

    -- Тест 5. Допустимый многострочный UPDATE: обе строки «на складе» -> «выдан»
    --         (WB0011RU и OZ0012RU лежат на складе)
    UPDATE Заказы SET Статус = 'выдан' WHERE ТрекНомер IN ('WB0011RU', 'OZ0012RU');
    SELECT N'Тест 5: многострочный UPDATE' AS Тест, COUNT(*) AS СтрокАудита
    FROM АудитИзменений
    WHERE Операция = 'UPDATE' AND Поле = N'Статус'
      AND НовоеЗначение = N'выдан';                             -- 2

ROLLBACK TRANSACTION;
GO

-- ---------- Блок Б. Нарушение бизнес-правила (транзакции нет: откат делает триггер)
-- Тест 6. «выдан» -> «на складе» запрещено
BEGIN TRY
    UPDATE Заказы SET Статус = 'на складе' WHERE ТрекНомер = 'WB0001RU';
    PRINT N'Тест 6: ОШИБКА — операция прошла, а должна быть отклонена';
END TRY
BEGIN CATCH
    PRINT CONCAT(N'Тест 6: ', ERROR_NUMBER(), N' — ', ERROR_MESSAGE());   -- 50020
END CATCH
SELECT N'Тест 6: статус после попытки' AS Тест, ТрекНомер, Статус
FROM Заказы WHERE ТрекНомер = 'WB0001RU';                      -- осталось «выдан»
GO

-- Тест 7. Многострочный UPDATE: WB0011RU (на складе -> выдан) допустим,
--         WB0027RU (в пути -> выдан) недопустим => откатывается ВЕСЬ оператор
BEGIN TRY
    UPDATE Заказы SET Статус = 'выдан' WHERE ТрекНомер IN ('WB0011RU', 'WB0027RU');
    PRINT N'Тест 7: ОШИБКА — операция прошла, а должна быть отклонена';
END TRY
BEGIN CATCH
    PRINT CONCAT(N'Тест 7: ', ERROR_NUMBER(), N' — ', ERROR_MESSAGE());   -- 50020
END CATCH
SELECT N'Тест 7: статусы после попытки' AS Тест, ТрекНомер, Статус
FROM Заказы WHERE ТрекНомер IN ('WB0011RU', 'WB0027RU');       -- «на складе» и «в пути»
SELECT N'Тест 7: строк в аудите' AS Тест, COUNT(*) AS Количество
FROM АудитИзменений;                                           -- 0
GO

-- Тест 8. Изменение, не затрагивающее статус, проходит
BEGIN TRANSACTION;
    UPDATE Заказы SET СтоимостьТовара = 1000.00 WHERE ТрекНомер = 'WB0027RU';
    SELECT N'Тест 8: изменение стоимости' AS Тест, Поле, СтароеЗначение, НовоеЗначение
    FROM АудитИзменений;                                       -- 1 строка: 870.00 -> 1000.00
ROLLBACK TRANSACTION;
GO

-- ---------- Блок В. INSTEAD OF DELETE (в транзакциях, затем откат)
-- Тест 9. Сотрудник с выдачами (СотрудникID = 2): физическое удаление
--         невозможно по FK, триггер переводит его в архив
BEGIN TRANSACTION;
    DELETE FROM Сотрудники WHERE СотрудникID = 2;
    SELECT N'Тест 9: сотрудник 2 после DELETE' AS Тест, СотрудникID, ФИО, Активен
    FROM Сотрудники WHERE СотрудникID = 2;                     -- строка есть, Активен = 0
ROLLBACK TRANSACTION;
GO

-- Тест 10. Многострочный DELETE: все операторы (СотрудникID 2, 3, 4, 5)
BEGIN TRANSACTION;
    DELETE FROM Сотрудники WHERE Должность = N'Оператор';
    SELECT N'Тест 10: в архиве' AS Тест, COUNT(*) AS Количество
    FROM Сотрудники WHERE Активен = 0;                         -- 4
    SELECT N'Тест 10: всего сотрудников' AS Тест, COUNT(*) AS Количество
    FROM Сотрудники;                                           -- 6
ROLLBACK TRANSACTION;
GO

/* ======================================================================
   7. ДЕМОНСТРАЦИЯ ДЛЯ ЗАЩИТЫ: нарушение правила -> триггер -> запись в аудите
   ====================================================================== */
-- 1) Допустимое изменение — попадает в аудит
UPDATE Заказы SET Статус = 'возврат' WHERE ТрекНомер = 'WB0011RU';   -- на складе -> возврат
-- 2) Нарушение правила — триггер отклоняет
BEGIN TRY
    UPDATE Заказы SET Статус = 'в пути' WHERE ТрекНомер = 'WB0011RU'; -- возврат -> в пути
END TRY
BEGIN CATCH
    PRINT CONCAT(ERROR_NUMBER(), N': ', ERROR_MESSAGE());
END CATCH
-- 3) Журнал аудита содержит только допустимое изменение
SELECT * FROM АудитИзменений ORDER BY АудитID;
-- 4) Возврат данных в исходное состояние после демонстрации
ALTER TABLE Заказы DISABLE TRIGGER ALL;
UPDATE Заказы SET Статус = 'на складе' WHERE ТрекНомер = 'WB0011RU';
ALTER TABLE Заказы ENABLE TRIGGER ALL;
DELETE FROM АудитИзменений;
GO
