/* ======================================================================
   1. БИЗНЕС-ПРАВИЛА И ТРЕБОВАНИЯ К АУДИТУ
   Аудит:   Заказы (INSERT / UPDATE статуса, ячейки и стоимости / DELETE).
   Правило: жизненный цикл заказа — допустимые переходы статуса:
              в пути   -> на складе | возврат
              на складе -> выдан | возврат
              выдан    -> возврат
            Остальные переходы запрещены (CHECK этого не выражает:
            нужно сравнивать старое и новое значение).
   INSTEAD OF: DELETE сотрудника заменяется признаком «архив» (Активен = 0),
            т.к. на сотрудника ссылаются выдачи.
   ====================================================================== */

/* ======================================================================
   2. ТАБЛИЦА АУДИТА И ПРИЗНАК «АРХИВ» ДЛЯ СОТРУДНИКОВ
   ====================================================================== */
IF OBJECT_ID(N'АудитИзменений', N'U') IS NULL
    CREATE TABLE АудитИзменений (
        АудитID         BIGINT IDENTITY(1,1) PRIMARY KEY,
        ИмяТаблицы      NVARCHAR(128) NOT NULL,
        КлючЗаписи      INT           NOT NULL,
        Операция        VARCHAR(6)    NOT NULL
            CHECK (Операция IN ('INSERT','UPDATE','DELETE')),
        Поле            NVARCHAR(128) NULL,
        СтароеЗначение  NVARCHAR(MAX) NULL,
        НовоеЗначение   NVARCHAR(MAX) NULL,
        Пользователь    NVARCHAR(128) NOT NULL DEFAULT SYSTEM_USER,
        ДатаИзменения   DATETIME2     NOT NULL DEFAULT SYSDATETIME()
    );
GO

-- Расширение схемы этапа 1: признак «архив» для справочника сотрудников
IF COL_LENGTH(N'Сотрудники', N'Активен') IS NULL
    ALTER TABLE Сотрудники
        ADD Активен BIT NOT NULL CONSTRAINT DF_Сотрудники_Активен DEFAULT 1;
GO

/* ======================================================================
   3. AFTER-ТРИГГЕРЫ АУДИТА
   ====================================================================== */

/* ----------------------------------------------------------------------
   trg_Заказы_AuditInsertDelete
   Назначение: фиксирует добавление и удаление заказов.
   Многострочность: набор строк из inserted / deleted, без курсоров.
   ---------------------------------------------------------------------- */
CREATE OR ALTER TRIGGER trg_Заказы_AuditInsertDelete
ON Заказы
AFTER INSERT, DELETE
AS
BEGIN
    SET NOCOUNT ON;

    -- при INSERT заполнена inserted, при DELETE — deleted
    INSERT INTO АудитИзменений (ИмяТаблицы, КлючЗаписи, Операция, НовоеЗначение)
    SELECT N'Заказы', i.ЗаказID, 'INSERT',
           CONCAT(N'ТрекНомер=', i.ТрекНомер, N'; КлиентID=', i.КлиентID,
                  N'; Статус=', i.Статус, N'; Стоимость=', i.СтоимостьТовара)
    FROM inserted i;

    INSERT INTO АудитИзменений (ИмяТаблицы, КлючЗаписи, Операция, СтароеЗначение)
    SELECT N'Заказы', d.ЗаказID, 'DELETE',
           CONCAT(N'ТрекНомер=', d.ТрекНомер, N'; КлиентID=', d.КлиентID,
                  N'; Статус=', d.Статус, N'; Стоимость=', d.СтоимостьТовара)
    FROM deleted d;
END
GO

/* ----------------------------------------------------------------------
   trg_Заказы_AuditUpdate
   Назначение: фиксирует изменения полей Статус, ЯчейкаID, СтоимостьТовара
               (по одной строке аудита на каждое изменённое поле).
   Многострочность: inserted и deleted сопоставляются по ЗаказID.
   ---------------------------------------------------------------------- */
CREATE OR ALTER TRIGGER trg_Заказы_AuditUpdate
ON Заказы
AFTER UPDATE
AS
BEGIN
    SET NOCOUNT ON;

    INSERT INTO АудитИзменений (ИмяТаблицы, КлючЗаписи, Операция, Поле, СтароеЗначение, НовоеЗначение)
    SELECT N'Заказы', i.ЗаказID, 'UPDATE', v.Поле, v.Старое, v.Новое
    FROM inserted i
    JOIN deleted d ON d.ЗаказID = i.ЗаказID
    CROSS APPLY (VALUES
        (N'Статус',          CAST(d.Статус          AS NVARCHAR(MAX)), CAST(i.Статус          AS NVARCHAR(MAX))),
        (N'ЯчейкаID',        CAST(d.ЯчейкаID        AS NVARCHAR(MAX)), CAST(i.ЯчейкаID        AS NVARCHAR(MAX))),
        (N'СтоимостьТовара', CAST(d.СтоимостьТовара AS NVARCHAR(MAX)), CAST(i.СтоимостьТовара AS NVARCHAR(MAX)))
    ) AS v (Поле, Старое, Новое)
    WHERE v.Старое <> v.Новое
       OR (v.Старое IS NULL     AND v.Новое IS NOT NULL)
       OR (v.Старое IS NOT NULL AND v.Новое IS NULL);
END
GO

/* ======================================================================
   4. ТРИГГЕР КОНТРОЛЯ БИЗНЕС-ПРАВИЛА
   ====================================================================== */

/* ----------------------------------------------------------------------
   trg_Заказы_ПроверкаСтатуса
   Назначение: запрещает недопустимые переходы статуса заказа.
   Поведение : при нарушении — откат всей операции и ошибка 50020.
   Многострочность: проверяются все изменённые строки; если нарушена
               хотя бы одна — откатывается весь UPDATE.
   ---------------------------------------------------------------------- */
CREATE OR ALTER TRIGGER trg_Заказы_ПроверкаСтатуса
ON Заказы
AFTER UPDATE
AS
BEGIN
    SET NOCOUNT ON;

    IF NOT UPDATE(Статус)
        RETURN;

    DECLARE @Сообщение NVARCHAR(2048);

    SELECT TOP (1)
           @Сообщение = CONCAT(N'Недопустимый переход статуса заказа ', i.ТрекНомер,
                               N': ', d.Статус, N' -> ', i.Статус)
    FROM inserted i
    JOIN deleted d ON d.ЗаказID = i.ЗаказID
    WHERE i.Статус <> d.Статус
      AND NOT EXISTS (SELECT 1
                      FROM (VALUES ('в пути',    'на складе'),
                                   ('в пути',    'возврат'),
                                   ('на складе', 'выдан'),
                                   ('на складе', 'возврат'),
                                   ('выдан',     'возврат')) AS доп (Откуда, Куда)
                      WHERE доп.Откуда = d.Статус AND доп.Куда = i.Статус)
    ORDER BY i.ЗаказID;

    IF @Сообщение IS NOT NULL
    BEGIN
        IF @@TRANCOUNT > 0
            ROLLBACK TRANSACTION;
        THROW 50020, @Сообщение, 1;
    END
END
GO

/* ======================================================================
   5. INSTEAD OF-ТРИГГЕР
   ====================================================================== */

/* ----------------------------------------------------------------------
   trg_Сотрудники_InsteadOfDelete
   Назначение: DELETE сотрудника не удаляет строку, а переводит её в архив
               (Активен = 0). История выдач сохраняется.
   Многострочность: UPDATE по набору строк из deleted.
   ---------------------------------------------------------------------- */
CREATE OR ALTER TRIGGER trg_Сотрудники_InsteadOfDelete
ON Сотрудники
INSTEAD OF DELETE
AS
BEGIN
    SET NOCOUNT ON;

    UPDATE с
    SET Активен = 0
    FROM Сотрудники с
    JOIN deleted d ON d.СотрудникID = с.СотрудникID;
END
GO

