-- 7.1. Заказы конкретного клиента с ячейкой и статусом
SELECT к.ФИО, з.ТрекНомер, п.Название AS Поставщик, з.Статус, з.ДатаПоступления
FROM Заказы з
JOIN Клиенты к ON к.КлиентID = з.КлиентID
JOIN Поставщики п ON п.ПоставщикID = з.ПоставщикID
WHERE к.ФИО = N'Алексеева Ольга Николаевна'
ORDER BY з.ДатаПоступления;

-- 7.2. Что сейчас лежит на складе (из представления)
SELECT * FROM v_ЗаказыНаСкладе ORDER BY ДатаПоступления;

-- 7.3. Дневная выручка по наложенным платежам (из представления)
