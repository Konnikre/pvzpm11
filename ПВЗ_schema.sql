-- ============================ 2. ТАБЛИЦЫ ================================

CREATE TABLE Клиенты (
    КлиентID       INT IDENTITY(1,1) PRIMARY KEY,
    ФИО            NVARCHAR(150) NOT NULL,
    Телефон        VARCHAR(20)   NOT NULL UNIQUE,
    Email          VARCHAR(100)  NULL,
    КодПолучения   CHAR(4)       NOT NULL
);
GO

CREATE TABLE Поставщики (
    ПоставщикID    INT IDENTITY(1,1) PRIMARY KEY,
    Название       NVARCHAR(100) NOT NULL,
    ИНН            CHAR(10)      NOT NULL UNIQUE,
    Телефон        VARCHAR(20)   NULL
);
GO

CREATE TABLE Сотрудники (
    СотрудникID    INT IDENTITY(1,1) PRIMARY KEY,
    ФИО            NVARCHAR(150) NOT NULL,
    Должность      NVARCHAR(50)  NOT NULL
        CHECK (Должность IN (N'Оператор', N'Администратор')),
    Логин          VARCHAR(50)   NOT NULL UNIQUE,
    ДатаПриёма     DATE          NOT NULL DEFAULT CAST(GETDATE() AS DATE)
);
GO

CREATE TABLE Ячейки (
    ЯчейкаID       INT IDENTITY(1,1) PRIMARY KEY,
    Номер          VARCHAR(10)   NOT NULL UNIQUE,
    Размер         VARCHAR(10)   NOT NULL
        CHECK (Размер IN ('S','M','L','XL')),
    Статус         VARCHAR(20)   NOT NULL DEFAULT 'свободна'
        CHECK (Статус IN ('свободна','занята'))
);
GO

CREATE TABLE Заказы (
    ЗаказID            INT IDENTITY(1,1) PRIMARY KEY,
    ТрекНомер          VARCHAR(30)   NOT NULL UNIQUE,
    КлиентID           INT           NOT NULL
        FOREIGN KEY REFERENCES Клиенты(КлиентID),
    ПоставщикID        INT           NOT NULL
        FOREIGN KEY REFERENCES Поставщики(ПоставщикID),
    ЯчейкаID           INT           NULL
        FOREIGN KEY REFERENCES Ячейки(ЯчейкаID) ON DELETE SET NULL,
    ДатаПоступления    DATETIME2     NOT NULL DEFAULT SYSDATETIME(),
    СрокХраненияДо     DATE          NOT NULL,
    СтоимостьТовара    DECIMAL(10,2) NOT NULL CHECK (СтоимостьТовара >= 0),
    НаложенныйПлатёж   BIT           NOT NULL DEFAULT 0,
    Статус             VARCHAR(20)   NOT NULL DEFAULT 'в пути'
        CHECK (Статус IN ('в пути','на складе','выдан','возврат'))
);
GO

CREATE TABLE Выдачи (
    ВыдачаID        INT IDENTITY(1,1) PRIMARY KEY,
    ЗаказID         INT           NOT NULL UNIQUE
        FOREIGN KEY REFERENCES Заказы(ЗаказID),
    СотрудникID     INT           NOT NULL
        FOREIGN KEY REFERENCES Сотрудники(СотрудникID),
    ДатаВыдачи      DATETIME2     NOT NULL DEFAULT SYSDATETIME(),
    СпособОплаты    VARCHAR(20)   NULL
        CHECK (СпособОплаты IN ('нал','карта')),
    СуммаОплачена   DECIMAL(10,2) NULL CHECK (СуммаОплачена >= 0)
);
GO

CREATE TABLE Возвраты (
    ВозвратID       INT IDENTITY(1,1) PRIMARY KEY,
    ЗаказID         INT           NOT NULL UNIQUE
        FOREIGN KEY REFERENCES Заказы(ЗаказID),
    Причина         NVARCHAR(200) NOT NULL,
    ДатаВозврата    DATE          NOT NULL DEFAULT CAST(GETDATE() AS DATE),
    Статус          VARCHAR(20)   NOT NULL DEFAULT 'оформлен'
        CHECK (Статус IN ('оформлен','отправлен поставщику','закрыт'))
);
GO

-- ========================== 3. ИНДЕКСЫ ==================================

CREATE INDEX IX_Заказы_Статус ON Заказы(Статус);
CREATE INDEX IX_Заказы_ДатаПоступления ON Заказы(ДатаПоступления);
CREATE INDEX IX_Выдачи_ДатаВыдачи ON Выдачи(ДатаВыдачи);
GO

-- ======================== 4. ПРЕДСТАВЛЕНИЯ ===============================

CREATE VIEW v_ЗаказыНаСкладе AS
SELECT з.ЗаказID, з.ТрекНомер, к.ФИО AS Клиент, я.Номер AS Ячейка,
       з.ДатаПоступления, з.СрокХраненияДо
FROM Заказы з
JOIN Клиенты к ON к.КлиентID = з.КлиентID
LEFT JOIN Ячейки я ON я.ЯчейкаID = з.ЯчейкаID
WHERE з.Статус = 'на складе';
GO

CREATE VIEW v_ДневнаяВыручка AS
SELECT CAST(в.ДатаВыдачи AS DATE) AS Дата,
       COUNT(*) AS КоличествоВыдач,
       SUM(в.СуммаОплачена) AS Выручка
FROM Выдачи в
GROUP BY CAST(в.ДатаВыдачи AS DATE);
GO

CREATE VIEW v_ЗагруженностьЯчеек AS
SELECT Размер, Статус, COUNT(*) AS Количество
FROM Ячейки
GROUP BY Размер, Статус;
GO

