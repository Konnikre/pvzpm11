-- 7.4. Загруженность ячеек хранения
SELECT * FROM v_ЗагруженностьЯчеек ORDER BY Размер, Статус;

-- 7.5. История выдач с ФИО сотрудника и клиента (JOIN на 3 таблицы)
SELECT в.ДатаВыдачи, к.ФИО AS Клиент, с.ФИО AS Сотрудник,
       з.ТрекНомер, в.СпособОплаты, в.СуммаОплачена
FROM Выдачи в
JOIN Заказы з ON з.ЗаказID = в.ЗаказID
JOIN Клиенты к ON к.КлиентID = з.КлиентID
JOIN Сотрудники с ON с.СотрудникID = в.СотрудникID
ORDER BY в.ДатаВыдачи DESC;
