/* ----------------------------------------------------------------------
   fn_ЗаказыКлиента
   Назначение: заказы клиента, поступившие за период (границы включены).
   Параметры : @КлиентID, @ДатаС, @ДатаПо
   Результат : таблица (ЗаказID, ТрекНомер, Поставщик, ДатаПоступления,
               Статус, СтоимостьТовара); пустая, если заказов нет
   Пример    : SELECT * FROM dbo.fn_ЗаказыКлиента(1, '2026-10-01', '2026-10-31');
   ---------------------------------------------------------------------- */
CREATE OR ALTER FUNCTION dbo.fn_ЗаказыКлиента (@КлиентID INT, @ДатаС DATE, @ДатаПо DATE)
RETURNS TABLE
AS
RETURN
(
    SELECT з.ЗаказID, з.ТрекНомер, п.Название AS Поставщик,
           з.ДатаПоступления, з.Статус, з.СтоимостьТовара
    FROM Заказы з
    JOIN Поставщики п ON п.ПоставщикID = з.ПоставщикID
    WHERE з.КлиентID = @КлиентID
      AND з.ДатаПоступления >= @ДатаС
      AND з.ДатаПоступления <  DATEADD(DAY, 1, @ДатаПо)
);
GO

/* ----------------------------------------------------------------------
   fn_ПросроченныеЗаказы
   Назначение: заказы на складе, у которых срок хранения истёк на дату
               @НаДату (кандидаты на возврат поставщику).
   Параметры : @НаДату — дата проверки
   Результат : таблица (ЗаказID, ТрекНомер, КлиентID, Клиент, Ячейка,
               СрокХраненияДо, ДнейПросрочки)
   Пример    : SELECT * FROM dbo.fn_ПросроченныеЗаказы('2026-11-02');
   ---------------------------------------------------------------------- */
CREATE OR ALTER FUNCTION dbo.fn_ПросроченныеЗаказы (@НаДату DATE)
RETURNS TABLE
AS
RETURN
(
    SELECT з.ЗаказID, з.ТрекНомер, з.КлиентID,
           dbo.fn_ФИОКратко(к.ФИО) AS Клиент,
           я.Номер AS Ячейка,
           з.СрокХраненияДо,
           dbo.fn_ДнейДоКонцаХранения(з.СрокХраненияДо, @НаДату) * -1 AS ДнейПросрочки
    FROM Заказы з
    JOIN Клиенты к ON к.КлиентID = з.КлиентID
    LEFT JOIN Ячейки я ON я.ЯчейкаID = з.ЯчейкаID
    WHERE з.Статус = 'на складе'
      AND з.СрокХраненияДо < @НаДату
);
GO

