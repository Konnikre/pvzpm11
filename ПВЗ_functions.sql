/* ----------------------------------------------------------------------
   fn_ФИОКратко
   Назначение: преобразует ФИО в краткую форму «Фамилия И.О.».
               Повторяющееся форматирование из отчётов и выборок.
   Параметры : @ФИО — полное ФИО (допустимо 1, 2 или 3 слова, NULL)
   Результат : NVARCHAR(150); NULL для NULL; одно слово возвращается как есть
   Пример    : SELECT dbo.fn_ФИОКратко(N'Иванова Анна Сергеевна'); -- Иванова А.С.
   ---------------------------------------------------------------------- */
CREATE OR ALTER FUNCTION dbo.fn_ФИОКратко (@ФИО NVARCHAR(150))
RETURNS NVARCHAR(150)
WITH SCHEMABINDING
AS
BEGIN
    IF @ФИО IS NULL
        RETURN NULL;

    DECLARE @Строка   NVARCHAR(150) = LTRIM(RTRIM(@ФИО));
    DECLARE @Позиция1 INT = CHARINDEX(N' ', @Строка);

    IF @Позиция1 = 0
        RETURN @Строка;                                   -- одно слово

    DECLARE @Фамилия  NVARCHAR(150) = LEFT(@Строка, @Позиция1 - 1);
    DECLARE @Остаток  NVARCHAR(150) = LTRIM(SUBSTRING(@Строка, @Позиция1 + 1, 150));
    DECLARE @Позиция2 INT = CHARINDEX(N' ', @Остаток);
    DECLARE @Итог     NVARCHAR(150) = @Фамилия + N' ' + LEFT(@Остаток, 1) + N'.';

    IF @Позиция2 > 0                                      -- есть отчество
        SET @Итог = @Итог + LEFT(LTRIM(SUBSTRING(@Остаток, @Позиция2 + 1, 150)), 1) + N'.';

    RETURN @Итог;
END
GO

/* ----------------------------------------------------------------------
   fn_ДнейДоКонцаХранения
   Назначение: сколько дней осталось до конца срока хранения заказа
               на указанную дату (отрицательное число — просрочка).
   Параметры : @СрокХраненияДо — Заказы.СрокХраненияДо
               @НаДату         — дата, на которую считаем
   Результат : INT; NULL, если любой из параметров NULL
   Пример    : SELECT dbo.fn_ДнейДоКонцаХранения('2026-11-05', '2026-10-29'); -- 7
   ---------------------------------------------------------------------- */
CREATE OR ALTER FUNCTION dbo.fn_ДнейДоКонцаХранения (@СрокХраненияДо DATE, @НаДату DATE)
RETURNS INT
WITH SCHEMABINDING
AS
BEGIN
    RETURN DATEDIFF(DAY, @НаДату, @СрокХраненияДо);
END
GO

