/* ----------------------------------------------------------------------
   fn_ЗагруженностьПоРазмерам
   Назначение: загруженность ячеек по размерам с итоговой строкой и
               статусом по порогам (в процентах занятости).
   Параметры : @ПорогВнимание — с этого процента статус «внимание»
               @ПорогКритично — с этого процента статус «критично»
   Результат : таблица (Размер, Всего, Занято, Свободно, ПроцентЗанятости,
               Статус); пустая, если пороги некорректны
               (NULL или @ПорогВнимание >= @ПорогКритично)
   Почему не inline: нужно несколько шагов — агрегация, добавление итоговой
               строки по условию, расчёт процента и классификация.
   Пример    : SELECT * FROM dbo.fn_ЗагруженностьПоРазмерам(60, 90);
   ---------------------------------------------------------------------- */
CREATE OR ALTER FUNCTION dbo.fn_ЗагруженностьПоРазмерам (@ПорогВнимание INT, @ПорогКритично INT)
RETURNS @Результат TABLE
(
    Размер            NVARCHAR(10) NOT NULL,
    Всего             INT          NOT NULL,
    Занято            INT          NOT NULL,
    Свободно          INT          NOT NULL,
    ПроцентЗанятости  DECIMAL(5,2) NULL,
    Статус            NVARCHAR(20) NULL
)
AS
BEGIN
    -- Ветвление 1: некорректные пороги — возвращаем пустую таблицу
    IF @ПорогВнимание IS NULL OR @ПорогКритично IS NULL OR @ПорогВнимание >= @ПорогКритично
        RETURN;

    -- Шаг 1: агрегация по размерам
    INSERT INTO @Результат (Размер, Всего, Занято, Свободно)
    SELECT Размер,
           COUNT(*),
           SUM(CASE WHEN Статус = 'занята'   THEN 1 ELSE 0 END),
           SUM(CASE WHEN Статус = 'свободна' THEN 1 ELSE 0 END)
    FROM Ячейки
    GROUP BY Размер;

    -- Шаг 2 (ветвление 2): итоговая строка, только если есть данные
    IF EXISTS (SELECT 1 FROM @Результат)
        INSERT INTO @Результат (Размер, Всего, Занято, Свободно)
        SELECT N'ИТОГО',
               COUNT(*),
               SUM(CASE WHEN Статус = 'занята'   THEN 1 ELSE 0 END),
               SUM(CASE WHEN Статус = 'свободна' THEN 1 ELSE 0 END)
        FROM Ячейки;

    -- Шаг 3: процент занятости
    UPDATE @Результат
    SET ПроцентЗанятости = CAST(Занято * 100.0 / Всего AS DECIMAL(5,2));

    -- Шаг 4: классификация по порогам
    UPDATE @Результат
    SET Статус = CASE WHEN ПроцентЗанятости >= @ПорогКритично THEN N'критично'
                      WHEN ПроцентЗанятости >= @ПорогВнимание THEN N'внимание'
                      ELSE N'норма' END;

    RETURN;
END
GO

/* ======================================================================
   4. РЕФАКТОРИНГ ПРОЦЕДУРЫ ЭТАПА 2: proc_Заказы_GetByStatus
   Теперь формат ФИО и расчёт остатка срока хранения берутся из функций
   (логика в одном месте, а не копируется в каждую выборку).
   Изменение результата: «Клиент» — в краткой форме, добавлена колонка
   ДнейДоКонцаХранения.
   ====================================================================== */
CREATE OR ALTER PROCEDURE proc_Заказы_GetByStatus
    @Статус VARCHAR(20)
AS
BEGIN
    SET NOCOUNT ON;
    IF @Статус NOT IN ('в пути','на складе','выдан','возврат')
    BEGIN
        THROW 50002, N'Недопустимое значение статуса', 1;
        RETURN;
    END

    SELECT з.ЗаказID, з.ТрекНомер,
           dbo.fn_ФИОКратко(к.ФИО) AS Клиент,
           я.Номер AS Ячейка,
           з.ДатаПоступления, з.СрокХраненияДо,
           dbo.fn_ДнейДоКонцаХранения(з.СрокХраненияДо, CAST(GETDATE() AS DATE)) AS ДнейДоКонцаХранения
    FROM Заказы з
    JOIN Клиенты к ON к.КлиентID = з.КлиентID
    LEFT JOIN Ячейки я ON я.ЯчейкаID = з.ЯчейкаID
    WHERE з.Статус = @Статус
    ORDER BY з.ДатаПоступления;
END
GO
-- Вызов: EXEC proc_Заказы_GetByStatus @Статус = 'на складе';

/* ======================================================================
   5. ДЕМОНСТРАЦИОННЫЕ ЗАПРОСЫ (применение функций)
   ====================================================================== */

-- 5.1. Скалярная в SELECT и ORDER BY
SELECT ФИО, dbo.fn_ФИОКратко(ФИО) AS ФИО_кратко
FROM Клиенты
ORDER BY dbo.fn_ФИОКратко(ФИО);

-- 5.2. Скалярная в SELECT, WHERE и ORDER BY: заказы, срок хранения которых
--      заканчивается не позже чем через 3 дня (на дату 29.10.2026)
SELECT ТрекНомер, СрокХраненияДо,
       dbo.fn_ДнейДоКонцаХранения(СрокХраненияДо, '2026-10-29') AS ДнейОсталось
FROM Заказы
WHERE Статус = 'на складе'
  AND dbo.fn_ДнейДоКонцаХранения(СрокХраненияДо, '2026-10-29') <= 3
ORDER BY ДнейОсталось;

-- 5.3. Inline-функция напрямую
SELECT * FROM dbo.fn_ЗаказыКлиента(1, '2026-10-01', '2026-10-31');

-- 5.4. Inline-функция в JOIN (CROSS APPLY): заказы и сумма по каждому клиенту
SELECT к.ФИО, COUNT(з.ЗаказID) AS Заказов, SUM(з.СтоимостьТовара) AS Сумма
FROM Клиенты к
CROSS APPLY dbo.fn_ЗаказыКлиента(к.КлиентID, '2026-10-01', '2026-10-31') з
GROUP BY к.ФИО
ORDER BY Заказов DESC, к.ФИО;

-- 5.5. Inline-функция в подзапросе: клиенты с просроченными заказами
SELECT ФИО, Телефон
FROM Клиенты
WHERE КлиентID IN (SELECT КлиентID FROM dbo.fn_ПросроченныеЗаказы('2026-11-02'));

-- 5.6. Многооператорная функция: загруженность и проблемные размеры
SELECT * FROM dbo.fn_ЗагруженностьПоРазмерам(60, 90)
ORDER BY CASE Размер WHEN N'S' THEN 1 WHEN N'M' THEN 2 WHEN N'L' THEN 3
                     WHEN N'XL' THEN 4 ELSE 5 END;

SELECT Размер, ПроцентЗанятости, Статус
FROM dbo.fn_ЗагруженностьПоРазмерам(40, 60)
WHERE Статус <> N'норма';

-- 5.7. Процедура после рефакторинга
EXEC proc_Заказы_GetByStatus @Статус = 'на складе';
GO

/* ======================================================================
   6. ТЕСТИРОВАНИЕ ФУНКЦИЙ (корректные данные, граничные значения, NULL)
   Столбец «Результат» должен содержать «Пройден» во всех строках.
   ====================================================================== */
;WITH т (Номер, Тест, Получено, Ожидалось) AS
(
    SELECT 1,  N'fn_ФИОКратко: три слова',
           dbo.fn_ФИОКратко(N'Иванова Анна Сергеевна'), N'Иванова А.С.'
    UNION ALL SELECT 2,  N'fn_ФИОКратко: два слова',
           dbo.fn_ФИОКратко(N'Иванова Анна'), N'Иванова А.'
    UNION ALL SELECT 3,  N'fn_ФИОКратко: одно слово',
           dbo.fn_ФИОКратко(N'Иванова'), N'Иванова'
    UNION ALL SELECT 4,  N'fn_ФИОКратко: NULL',
           dbo.fn_ФИОКратко(NULL), NULL
    UNION ALL SELECT 5,  N'fn_ДнейДоКонцаХранения: срок в будущем',
           CAST(dbo.fn_ДнейДоКонцаХранения('2026-11-05', '2026-10-29') AS NVARCHAR(20)), N'7'
    UNION ALL SELECT 6,  N'fn_ДнейДоКонцаХранения: просрочка',
           CAST(dbo.fn_ДнейДоКонцаХранения('2026-10-20', '2026-10-29') AS NVARCHAR(20)), N'-9'
    UNION ALL SELECT 7,  N'fn_ДнейДоКонцаХранения: последний день',
           CAST(dbo.fn_ДнейДоКонцаХранения('2026-10-29', '2026-10-29') AS NVARCHAR(20)), N'0'
    UNION ALL SELECT 8,  N'fn_ДнейДоКонцаХранения: NULL',
           CAST(dbo.fn_ДнейДоКонцаХранения(NULL, '2026-10-29') AS NVARCHAR(20)), NULL
    UNION ALL SELECT 9,  N'fn_ЗаказыКлиента: клиент 1, октябрь 2026',
           CAST((SELECT COUNT(*) FROM dbo.fn_ЗаказыКлиента(1, '2026-10-01', '2026-10-31')) AS NVARCHAR(20)), N'3'
    UNION ALL SELECT 10, N'fn_ЗаказыКлиента: период без заказов',
           CAST((SELECT COUNT(*) FROM dbo.fn_ЗаказыКлиента(1, '2025-01-01', '2025-01-31')) AS NVARCHAR(20)), N'0'
    UNION ALL SELECT 11, N'fn_ЗаказыКлиента: граница периода включена',
           CAST((SELECT COUNT(*) FROM dbo.fn_ЗаказыКлиента(1, '2026-10-20', '2026-10-20')) AS NVARCHAR(20)), N'1'
    UNION ALL SELECT 12, N'fn_ПросроченныеЗаказы: на 02.11.2026',
           CAST((SELECT COUNT(*) FROM dbo.fn_ПросроченныеЗаказы('2026-11-02')) AS NVARCHAR(20)), N'3'
    UNION ALL SELECT 13, N'fn_ПросроченныеЗаказы: на 29.10.2026 (просроченных нет)',
           CAST((SELECT COUNT(*) FROM dbo.fn_ПросроченныеЗаказы('2026-10-29')) AS NVARCHAR(20)), N'0'
    UNION ALL SELECT 14, N'fn_ЗагруженностьПоРазмерам(60, 90): число строк',
           CAST((SELECT COUNT(*) FROM dbo.fn_ЗагруженностьПоРазмерам(60, 90)) AS NVARCHAR(20)), N'5'
    UNION ALL SELECT 15, N'fn_ЗагруженностьПоРазмерам(60, 90): статус размера S',
           (SELECT Статус FROM dbo.fn_ЗагруженностьПоРазмерам(60, 90) WHERE Размер = N'S'), N'внимание'
    UNION ALL SELECT 16, N'fn_ЗагруженностьПоРазмерам(40, 60): статус размера S',
           (SELECT Статус FROM dbo.fn_ЗагруженностьПоРазмерам(40, 60) WHERE Размер = N'S'), N'критично'
    UNION ALL SELECT 17, N'fn_ЗагруженностьПоРазмерам(90, 60): пороги перепутаны',
           CAST((SELECT COUNT(*) FROM dbo.fn_ЗагруженностьПоРазмерам(90, 60)) AS NVARCHAR(20)), N'0'
)
SELECT Номер, Тест, Получено, Ожидалось,
       CASE WHEN Получено = Ожидалось OR (Получено IS NULL AND Ожидалось IS NULL)
            THEN N'Пройден' ELSE N'ОШИБКА' END AS Результат
FROM т
ORDER BY Номер;
GO
